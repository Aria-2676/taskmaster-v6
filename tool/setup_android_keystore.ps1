# Generates the Android release keystore and writes android/key.properties.
#
# Usage (in YOUR OWN PowerShell window, not via an agent):
#   powershell -ExecutionPolicy Bypass -File tool\setup_android_keystore.ps1
#
# The password is typed by YOU and never leaves this machine.
# Keep both the .jks file and the password forever: lose them and you can never
# publish an update for an already-installed build again (users would have to
# uninstall and reinstall, losing their data).

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$keystoreDir = 'D:\Dev\keystore'
$keystoreFile = Join-Path $keystoreDir 'taskmaster-release.jks'
$keyAlias = 'taskmaster'
$keyPropertiesFile = Join-Path $repoRoot 'android\key.properties'

Write-Host ''
Write-Host '=== Android release keystore setup ===' -ForegroundColor Cyan
Write-Host "keystore : $keystoreFile"
Write-Host "alias    : $keyAlias"
Write-Host "config   : $keyPropertiesFile"
Write-Host ''

if (Test-Path -LiteralPath $keystoreFile) {
    Write-Host 'Keystore already exists - nothing to do.' -ForegroundColor Yellow
    Write-Host 'Only delete it if you accept that existing installs can no' -ForegroundColor Yellow
    Write-Host 'longer be updated in place.' -ForegroundColor Yellow
    exit 1
}

$keytool = Join-Path $env:JAVA_HOME 'bin\keytool.exe'
if (-not (Test-Path -LiteralPath $keytool)) {
    throw "keytool not found at $keytool - check that JAVA_HOME points to a JDK."
}

New-Item -ItemType Directory -Force -Path $keystoreDir | Out-Null

$secure1 = Read-Host -Prompt 'Password for the keystore (8+ chars, 20+ recommended)' -AsSecureString
$secure2 = Read-Host -Prompt 'Repeat the password' -AsSecureString
$plain1 = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure1))
$plain2 = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure2))

if ($plain1 -ne $plain2) { throw 'Passwords do not match.' }
if ($plain1.Length -lt 8) { throw 'Password must be at least 8 characters.' }

# keytool -v writes its progress banner to stderr. Under
# $ErrorActionPreference='Stop' PowerShell 5.1 escalates native stderr to a
# terminating NativeCommandError, which would abort before key.properties is
# written even though the keystore was created successfully. Relax the
# preference for this call and judge purely by exit code.
$prevEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
& $keytool -genkeypair -v `
    -keystore $keystoreFile `
    -storetype PKCS12 `
    -keyalg RSA `
    -keysize 2048 `
    -validity 10000 `
    -alias $keyAlias `
    -storepass $plain1 `
    -keypass $plain1 `
    -dname 'CN=TaskMaster, OU=Personal, O=Personal, L=City, ST=City, C=CN'
$keytoolExit = $LASTEXITCODE
$ErrorActionPreference = $prevEap

if ($keytoolExit -ne 0) { throw "keytool failed with exit code $keytoolExit" }
if (-not (Test-Path -LiteralPath $keystoreFile)) { throw 'keytool reported success but the keystore file is missing.' }

# java.util.Properties.load() (used by android/app/build.gradle.kts) treats a
# backslash as an escape character: \t becomes a TAB, and unknown escapes drop
# the backslash entirely. A Windows path written verbatim is therefore silently
# corrupted -- 'D:\Dev\keystore\taskmaster-release.jks' is read as
# "D:Devkeystore<TAB>askmaster-release.jks", and the build then fails with
# "Keystore file ... not found". Doubling every backslash round-trips correctly.
$storeFileEscaped = $keystoreFile -replace '\\', '\\'

$lines = @(
    '# Generated by tool/setup_android_keystore.ps1 -- DO NOT COMMIT.',
    '# Read by android/app/build.gradle.kts for release signing.',
    '# NOTE: java.util.Properties.load() treats backslash as an escape character',
    '# (\t -> TAB), so Windows paths MUST use doubled backslashes.',
    "storePassword=$plain1",
    "keyPassword=$plain1",
    "keyAlias=$keyAlias",
    "storeFile=$storeFileEscaped"
)
Set-Content -LiteralPath $keyPropertiesFile -Value $lines -Encoding ASCII

# Keep a second copy next to the keystore: losing the repo checkout should not
# mean losing the ability to sign updates.
Copy-Item -LiteralPath $keyPropertiesFile -Destination (Join-Path $keystoreDir 'key.properties') -Force

$plain1 = $null
$plain2 = $null

Write-Host ''
Write-Host 'DONE. Keep these two things safe forever:' -ForegroundColor Green
Write-Host "  1) $keystoreFile"
Write-Host '  2) the password (put it in a password manager)'
Write-Host ''
Write-Host "Credentials copy: $keystoreDir\key.properties" -ForegroundColor Green
Write-Host 'Back the whole folder up to cloud storage or a USB stick.' -ForegroundColor Green
Write-Host ''
Write-Host 'Verify with:  flutter build apk --release' -ForegroundColor Cyan
