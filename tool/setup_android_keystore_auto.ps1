# Generates the Android release keystore with an agent-generated password.
#
# Usage (in YOUR OWN PowerShell window):
#   powershell -ExecutionPolicy Bypass -File tool\setup_android_keystore_auto.ps1
#
# DIFFERENCE from setup_android_keystore.ps1:
#   This variant GENERATES the password itself instead of prompting.
#   Use it only when the password has already been disclosed elsewhere
#   (e.g. in a chat log) -- in that case treat the keystore as LOCAL-TEST ONLY
#   and mint a clean one before any real distribution.
#
# The generated password is written to D:\Dev\keystore\PASSWORD.txt and shown in
# this window exactly once. Nothing is sent anywhere; the keystore is NOT in git.

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$keystoreDir = 'D:\Dev\keystore'
$keystoreFile = Join-Path $keystoreDir 'taskmaster-release.jks'
$keyAlias = 'taskmaster'
$keyPropertiesFile = Join-Path $repoRoot 'android\key.properties'
$passwordFile = Join-Path $keystoreDir 'PASSWORD.txt'

Write-Host ''
Write-Host '=== Android release keystore (auto password) ===' -ForegroundColor Cyan
Write-Host "keystore : $keystoreFile"
Write-Host "alias    : $keyAlias"
Write-Host "config   : $keyPropertiesFile"
Write-Host ''

if (Test-Path -LiteralPath $keystoreFile) {
    Write-Host 'Keystore already exists - nothing to do.' -ForegroundColor Yellow
    Write-Host 'Only delete it if you accept that existing installs can no' -ForegroundColor Yellow
    Write-Host 'longer be updated in place.' -ForegroundColor Yellow
    exit 1
}

$keytool = Join-Path $env:JAVA_HOME 'bin\keytool.exe'
if (-not (Test-Path -LiteralPath $keytool)) {
    throw "keytool not found at $keytool - check that JAVA_HOME points to a JDK."
}

New-Item -ItemType Directory -Force -Path $keystoreDir | Out-Null

# 24 chars from an unambiguous alphabet; generated in-process, never passed as
# a shell argument, so it does not land in any command history.
$alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
$bytes = New-Object byte[] 24
[System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$chars = for ($i = 0; $i -lt 24; $i++) { $alphabet[$bytes[$i] % $alphabet.Length] }
$plain = -join $chars

# keytool -v prints its progress banner to stderr. PowerShell 5.1 turns native
# stderr into a NativeCommandError, and the script-level
# $ErrorActionPreference='Stop' would abort on it -- before key.properties is
# written, even though the keystore was created. Use cmd's `2>nul` redirection
# (handled by the OS, outside PowerShell's error stream) and keep the
# preference relaxed for the duration of the call.
$prevEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
cmd /c "`"$keytool`" -genkeypair -v -keystore `"$keystoreFile`" -storetype PKCS12 -keyalg RSA -keysize 2048 -validity 10000 -alias $keyAlias -storepass $plain -keypass $plain -dname `"CN=TaskMaster, OU=Personal, O=Personal, L=City, ST=City, C=CN`" 2>nul"
$keytoolExit = $LASTEXITCODE
$ErrorActionPreference = $prevEap

if ($keytoolExit -ne 0) { throw "keytool failed with exit code $keytoolExit" }
if (-not (Test-Path -LiteralPath $keystoreFile)) { throw 'keytool reported success but the keystore file is missing.' }

# java.util.Properties.load() (used by android/app/build.gradle.kts) treats a
# backslash as an escape character: \t becomes a TAB, and unknown escapes drop
# the backslash entirely. A Windows path written verbatim is therefore silently
# corrupted -- 'D:\Dev\keystore\taskmaster-release.jks' is read as
# "D:Devkeystore<TAB>askmaster-release.jks", and the build then fails with
# "Keystore file ... not found". Doubling every backslash round-trips correctly.
$storeFileEscaped = $keystoreFile -replace '\\', '\\'

$lines = @(
    '# Generated by tool/setup_android_keystore_auto.ps1 -- DO NOT COMMIT.',
    '# Read by android/app/build.gradle.kts for release signing.',
    '# NOTE: java.util.Properties.load() treats backslash as an escape character',
    '# (\t -> TAB), so Windows paths MUST use doubled backslashes.',
    "storePassword=$plain",
    "keyPassword=$plain",
    "keyAlias=$keyAlias",
    "storeFile=$storeFileEscaped"
)
Set-Content -LiteralPath $keyPropertiesFile -Value $lines -Encoding ASCII
Copy-Item -LiteralPath $keyPropertiesFile -Destination (Join-Path $keystoreDir 'key.properties') -Force

# The password is the one thing that cannot be recovered from the keystore.
Set-Content -LiteralPath $passwordFile -Value @(
    'TaskMaster Android release keystore password',
    "alias:  $keyAlias",
    "file:   $keystoreFile",
    '',
    $plain
) -Encoding ASCII

Write-Host ''
Write-Host 'DONE. Password (also saved to PASSWORD.txt):' -ForegroundColor Green
Write-Host "  $plain" -ForegroundColor Green
Write-Host ''
Write-Host 'KEEP SAFE FOREVER:' -ForegroundColor Yellow
Write-Host "  1) $keystoreFile"
Write-Host "  2) the password above"
Write-Host ''
Write-Host 'Next: powershell -ExecutionPolicy Bypass -File tool\backup_android_keystore.ps1'
Write-Host 'and copy the produced backup somewhere off this machine.' -ForegroundColor Cyan
Write-Host ''
